"""On-disk layout of a generated dataset: one folder per split, one folder per run inside it.

    <dataset>/train/<run_id>/   <dataset>/val/<run_id>/   <dataset>/test/<run_id>/

Datasets generated by older versions kept every run in <dataset>/runs/<run_id>/; those still load.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional, Union

SPLITS = ("train", "val", "test")


def run_dir(dataset_dir: Union[str, Path], run_id: str, split: Optional[str]) -> Path:
    """Folder of one run. `split` comes from the dataset manifest (`runs[run_id]["split"]`)."""
    root = Path(dataset_dir)
    if split:
        new = root / split / run_id
        if new.is_dir() or not (root / "runs" / run_id).is_dir():
            return new
    return root / "runs" / run_id          # legacy flat layout
